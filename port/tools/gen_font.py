"""Anti-aliased bitmap fonts for the SDK port from assets/fonts/InterTight[wght].ttf (OFL): three sizes as
4-bit alpha glyphs in a C header. Pillow only.
  gen_font.py OUT.h
Layout (port/app/screen.c pf_*): per glyph w, h, left, top (from the baseline, up), advance, offset into
the pixel pool; pixels row-major, two per byte (high nibble first)."""
import sys
from pathlib import Path

from PIL import Image, ImageDraw, ImageFont

ROOT = Path(__file__).resolve().parents[2]
FONT = ROOT / "assets/fonts/InterTight[wght].ttf"
ALL = "".join(chr(c) for c in range(32, 127))
BIG = " #+/0123456789ABCDEFGabcdefghijklmnopqrstuvwxyz"       # the chord names
FONTS = [("PF_S", 13, 560, ALL), ("PF_M", 19, 600, ALL), ("PF_X", 40, 650, BIG)]


def glyphs(size, weight, chars):
    f = ImageFont.truetype(str(FONT), size)
    try:
        f.set_variation_by_axes([weight])
    except Exception:
        pass
    ascent, descent = f.getmetrics()
    out = []
    for ch in chars:
        l, t, r, b = f.getbbox(ch, anchor="ls")                 # relative to the baseline at y 0
        w, h = max(r - l, 0), max(b - t, 0)
        adv = int(round(f.getlength(ch)))
        if w and h:
            im = Image.new("L", (w, h), 0)
            ImageDraw.Draw(im).text((-l, -t), ch, font=f, fill=255, anchor="ls")
            px = [im.getpixel((x, y)) >> 4 for y in range(h) for x in range(w)]
        else:
            w = h = 0
            px = []
        out.append((ch, w, h, l, -t, adv, px))
    return ascent, descent, out


def main(out):
    lines = ["/* generated by port/tools/gen_font.py from assets/fonts/InterTight[wght].ttf (OFL): do not edit */",
             "typedef struct { uint8_t w, h; int8_t left, top; uint8_t adv; uint16_t off; } pf_glyph_t;",
             "typedef struct { uint8_t size, ascent, first, count; const pf_glyph_t *g; const uint8_t *px; } pf_font_t;"]
    for name, size, weight, chars in FONTS:
        ascent, descent, gl = glyphs(size, weight, chars)
        pool, table = [], []
        first = ord(chars[0])
        by = {ch: g for g in gl for ch in [g[0]]}
        for code in range(first, ord(chars[-1]) + 1):
            g = by.get(chr(code))
            if not g:
                table.append("{0, 0, 0, 0, %d, 0}" % int(round(size * 0.3)))
                continue
            ch, w, h, l, top, adv, px = g
            off = len(pool)
            packed = px + ([0] if len(px) % 2 else [])
            pool.extend(packed[i] << 4 | packed[i + 1] for i in range(0, len(packed), 2))
            table.append("{%d, %d, %d, %d, %d, %d}" % (w, h, l, top, adv, off))
        lines.append("static const uint8_t %s_PX[%d] = {%s};" % (name, max(len(pool), 1), ",".join(str(b) for b in pool) or "0"))
        lines.append("static const pf_glyph_t %s_G[%d] = {%s};" % (name, len(table), ",".join(table)))
        lines.append("static const pf_font_t %s = {%d, %d, %d, %d, %s_G, %s_PX};" % (name, size, ascent, first, len(table), name, name))
        print("%s: %d px, %d glyphs, %d bytes" % (name, size, len(table), len(pool)))
    Path(out).write_text("\n".join(lines) + "\n")


if __name__ == "__main__":
    main(sys.argv[1] if len(sys.argv) > 1 else "fonts.h")
